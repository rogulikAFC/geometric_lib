def area(a:float) -> float:
    """
    Принимает значение длины стороны квадрата a, возвращает площадь квадрата.

    Параметры:
        a (float): длина стороны квадрата

    Возвращаемое значение:
        area (float): площадь квадрата
    """
    return a * a


def perimeter(a:float) -> float:
    """
    Принимает значение длины стороны квадрата a, возвращает периметр квадрата.

    Параметры:
        a (float): длина стороны квадрата

    Возвращаемое значение:
        perimeter (float): периметр квадрата
    """
    return 4 * a
